let UID = 1;

export class Entity {
  constructor(x, y) {
    this.id = UID++;
    this.x = x;
    this.y = y;
    this.r = 5;
    this.vx = 0; // инерционное движение — см. sim/Movement.js
    this.vy = 0;
    this.dead = false;
  }
}
