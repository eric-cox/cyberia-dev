// ============================================================
//  sim/Movement — инерционное движение по ячейкам.
//
//  Скорость сущности не равна вводу напрямую: она «догоняет»
//  желаемую скорость. Темп догоняния зависит от инерции ячейки:
//    grip = 1 - inertia
//    снег (0.2)  → отзывчивое управление;
//    лёд  (0.5)  → заметное скольжение;
//    каток (1.0) → движение продолжается само, развернуться
//                  почти невозможно — чистое скольжение.
// ============================================================

export function steer(e, desiredX, desiredY, map, dt) {
  const cell = map.cellAt(e.x, e.y);
  const grip = 1 - cell.inertia;
  const response = 0.7 + grip * 12; // 1/сек: как быстро скорость меняется
  const k = Math.min(1, response * dt);
  e.vx += (desiredX - e.vx) * k;
  e.vy += (desiredY - e.vy) * k;
}
