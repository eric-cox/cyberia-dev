// ============================================================
//  core/Rng — детерминированные генераторы.
//  Один сид → один и тот же мир. Это основа и для процедурной
//  генерации, и для будущей синхронизации в мультиплеере
//  (сервер рассылает сид, клиенты строят одинаковую карту).
// ============================================================

// mulberry32 — стандартный быстрый детерминированный PRNG.
// Возвращает функцию, выдающую числа [0, 1). Одинаковый сид
// всегда даёт одинаковую последовательность — основа
// воспроизводимой генерации мира.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
